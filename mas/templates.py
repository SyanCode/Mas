def fill(template: str, **values: object) -> str:
    out = template
    for key, value in values.items():
        out = out.replace(f"@@{key.upper()}@@", str(value))
    return out


def vhost(app_id: str, domain: str, body: str, https: bool, upstream: str = "", aliases: list[str] = ()) -> str:
    """``server_name`` lists the domain and its aliases; the certificate is the one named after the domain."""
    server = HTTPS_SERVERS if https else HTTP_SERVER
    server = server.replace("server_name @@DOMAIN@@;", "server_name @@NAMES@@;")
    return fill(HEADER, app=app_id) + upstream + fill(server, names=" ".join([domain, *aliases]), domain=domain,
                                                      app=app_id, body=body)


def upstream_name(app_id: str) -> str:
    return "mas_app_" + app_id.replace("-", "_")


def upstream_block(app_id: str, servers: list[str]) -> str:
    """Load balancing over several backends; one that fails is skipped for 10 s (passive check)."""
    lines = "".join(f"    server {s} max_fails=2 fail_timeout=10s;\n" for s in servers)
    return f"upstream {upstream_name(app_id)} {{\n    least_conn;\n{lines}}}\n\n"


# An app that sleeps when nobody visits it: the first request finds no backend, Mas starts the app and
# answers a "starting" page that refreshes until the app answers.
WAKE_LOCATION = """
    location @mas_wake {
        proxy_pass http://127.0.0.1:@@MAS_PORT@@/api/wake/@@APP@@;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
    }
"""


def proxy_body(port: int, pages_dir: str, upstream: str | None = None, app_id: str = "app",
               wake_port: int | None = None) -> str:
    # With an upstream, a request that hits a restarting or dead backend is retried on the next one.
    next_upstream = ("\n        proxy_next_upstream error timeout http_502 http_503 http_504;"
                     "\n        proxy_next_upstream_tries 3;") if upstream else ""
    body = fill(PROXY_BODY, target=upstream or f"127.0.0.1:{port}", next_upstream=next_upstream,
                pages=pages_dir, page="deploying", app=app_id)
    if wake_port:
        body = body.replace("error_page 502 503 504 =503 /__mas/status.html;", "error_page 502 503 504 = @mas_wake;", 1)
        body += fill(WAKE_LOCATION, mas_port=wake_port, app=app_id)
    return body


def supabase_body(port: int, pages_dir: str, studio_allow: list[str] = ()) -> str:
    allow = "".join(f"        allow {net};\n" for net in studio_allow)
    return fill(SUPABASE_BODY, port=port, pages=pages_dir, page="deploying", allow=allow)


def placeholder_body(pages_dir: str, page: str) -> str:
    return fill(PLACEHOLDER_BODY, pages=pages_dir, page=page)


