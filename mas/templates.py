"""nginx vhost and systemd unit templates for deployed apps.

Placeholders are ``@@NAME@@`` because nginx itself uses ``$`` and ``{}``.
"""

from __future__ import annotations

HEADER = "# Generated by Mas for app @@APP@@. Changes are overwritten on the next deploy.\n"

# Shared by every proxied app (websocket upgrade); lives in conf.d once.
UPGRADE_MAP = """# Generated by Mas.
map $http_upgrade $mas_connection_upgrade {
    default upgrade;
    ''      close;
}
"""

PROXY_BODY = """
    location / {
        proxy_pass http://127.0.0.1:@@PORT@@;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $mas_connection_upgrade;
        proxy_read_timeout 120s;
    }
"""

STATIC_BODY = """
    root @@ROOT@@;
    index index.html;
    location / {
        try_files $uri $uri/ $uri.html =404;
    }
    location ~ /\\.(?!well-known) {
        deny all;
    }
"""

PHP_BODY = """
    root @@ROOT@@;
    index index.php index.html;
    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }
    location ~ \\.php$ {
        include snippets/fastcgi-php.conf;
        fastcgi_pass unix:@@FPM@@;
    }
    location ~ /\\.(?!well-known) {
        deny all;
    }
"""

HTTP_SERVER = """server {
    listen 80;
    listen [::]:80;
    server_name @@DOMAIN@@;
    client_max_body_size 20m;
    access_log /var/log/nginx/mas-app-@@APP@@.access.log;
    error_log /var/log/nginx/mas-app-@@APP@@.error.log;
@@BODY@@}
"""

HTTPS_SERVERS = """server {
    listen 80;
    listen [::]:80;
    server_name @@DOMAIN@@;
    return 301 https://$host$request_uri;
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name @@DOMAIN@@;
    ssl_certificate /etc/letsencrypt/live/@@DOMAIN@@/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/@@DOMAIN@@/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    add_header Strict-Transport-Security "max-age=31536000" always;
    client_max_body_size 20m;
    access_log /var/log/nginx/mas-app-@@APP@@.access.log;
    error_log /var/log/nginx/mas-app-@@APP@@.error.log;
@@BODY@@}
"""

UNIT = """# Generated by Mas for app @@APP@@ (@@REPO@@). Changes are overwritten on the next deploy.
[Unit]
Description=Mas app @@APP@@ (@@REPO@@)
After=network.target

[Service]
Type=simple
User=@@USER@@
Group=@@USER@@
WorkingDirectory=@@CURRENT@@
EnvironmentFile=-@@ENV_FILE@@
Environment="PORT=@@PORT@@" "HOST=127.0.0.1" "HOSTNAME=127.0.0.1" "NODE_ENV=production" "PATH=@@PATH@@"
ExecStart=@@EXEC@@
Restart=on-failure
RestartSec=3
NoNewPrivileges=yes
ProtectSystem=full
ProtectHome=yes
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
"""


def fill(template: str, **values: object) -> str:
    out = template
    for key, value in values.items():
        out = out.replace(f"@@{key.upper()}@@", str(value))
    return out


def vhost(app_id: str, domain: str, body: str, https: bool) -> str:
    server = HTTPS_SERVERS if https else HTTP_SERVER
    return fill(HEADER, app=app_id) + fill(server, domain=domain, app=app_id, body=body)


def proxy_body(port: int) -> str:
    return fill(PROXY_BODY, port=port)


def static_body(root: str) -> str:
    return fill(STATIC_BODY, root=root)


def php_body(root: str, fpm_socket: str) -> str:
    return fill(PHP_BODY, root=root, fpm=fpm_socket)


def systemd_quote(command: str) -> str:
    """ExecStart value running ``command`` through /bin/sh (systemd quoting rules)."""
    escaped = command.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    return f'/bin/sh -c "exec {escaped}"'


def unit(app_id: str, repo: str, user: str, current: str, env_file: str, port: int, path: str, exec_start: str) -> str:
    return fill(UNIT, app=app_id, repo=repo, user=user, current=current, env_file=env_file, port=port,
                path=path, exec=exec_start)
