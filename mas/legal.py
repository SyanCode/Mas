def _privacy(p: dict, services: list, lang: str, host: str, today: date, miss: list[str]) -> str:
    g = lambda k: _v(p, k, lang, miss)  # noqa: E731
    months = p["retention_months"] or None
    if not months:
        miss.append("retention_months")
    keep = months or TODO[lang]
    contact = p["contact_form"] == "true" or not p["contact_form"]
    names = {s["name"] for s in services}
    us = sorted(s["name"] for s in services if "US" in s["region"])
    dpo = p["dpo"]  # (no quote reuse inside f-strings: the server may run Python 3.11)
    dpo_fr = f" · Délégué à la protection des données : {dpo}" if dpo else ""
    dpo_en = f" · Data protection officer: {dpo}" if dpo else ""
    if lang == "fr":
        lines = [f"# Politique de confidentialité", "", f"*Dernière mise à jour : {today.strftime('%d/%m/%Y')}*", "",
                 "## Qui est responsable de vos données ?", "",
                 f"**{g('company')}**, {g('address')}, est responsable du traitement des données personnelles collectées sur **{host}**. "
                 f"Contact : {g('email')}{dpo_fr}.", "",
                 "## Quelles données, pourquoi et sur quelle base ?", "",
                 "| Finalité | Données | Base légale | Durée de conservation |", "|---|---|---|---|"]
        if contact:
            lines.append(f"| Répondre à vos messages (formulaire, e-mail) | nom, e-mail, message | intérêt légitime / mesures précontractuelles | {keep} mois après le dernier échange |")
        if p["newsletter"] == "true":
            lines.append("| Envoi de la lettre d'information | e-mail | consentement | jusqu'au retrait du consentement (3 ans sans activité) |")
        if any(s["category"] in ("analytics", "exempt") for s in services):
            lines.append("| Mesure d'audience | identifiants en ligne, pages vues | consentement (cookies) | 13 mois maximum |")
        if any(s["category"] == "marketing" for s in services):
            lines.append("| Publicité et suivi des campagnes | identifiants en ligne, navigation | consentement (cookies) | 13 mois maximum |")
        lines += ["", "## Destinataires", "",
                  f"Vos données sont destinées à {g('company')} et à ses prestataires techniques : l'hébergeur ({g('host_name')})"
                  + (f", ainsi que : {', '.join(sorted(names))}." if names else ".") + " Elles ne sont pas vendues.", ""]
        if us:
            lines += ["## Transferts hors de l'Union européenne", "",
                      f"Certains services ({', '.join(us)}) peuvent traiter des données aux États-Unis. Ces transferts s'appuient sur les garanties prévues par le RGPD (décision d'adéquation / clauses contractuelles types).", ""]
        lines += ["## Vos droits", "",
                  f"Vous disposez des droits d'accès, de rectification, d'effacement, de limitation, d'opposition et de portabilité, ainsi que du droit de retirer votre consentement à tout moment. Pour les exercer, écrivez à {g('email')}. Nous répondons sous un mois. "
                  "Vous pouvez aussi introduire une réclamation auprès de la CNIL (www.cnil.fr).", "",
                  "## Cookies", "", "Voir la [politique de cookies](/politique-de-cookies).", ""]
        return "\n".join(lines)
    lines = ["# Privacy policy", "", f"*Last updated: {today.isoformat()}*", "", "## Who is responsible for your data?", "",
             f"**{g('company')}**, {g('address')}, is the controller of the personal data collected on **{host}**. "
             f"Contact: {g('email')}{dpo_en}.", "",
             "## What data, why and on what basis?", "", "| Purpose | Data | Legal basis | Retention |", "|---|---|---|---|"]
    if contact:
        lines.append(f"| Answering your messages (form, e-mail) | name, e-mail, message | legitimate interest / pre-contractual steps | {keep} months after the last exchange |")
    if p["newsletter"] == "true":
        lines.append("| Sending the newsletter | e-mail | consent | until consent is withdrawn (3 years without activity) |")
    if any(s["category"] in ("analytics", "exempt") for s in services):
        lines.append("| Audience measurement | online identifiers, pages viewed | consent (cookies) | 13 months at most |")
    if any(s["category"] == "marketing" for s in services):
        lines.append("| Advertising and campaign tracking | online identifiers, browsing | consent (cookies) | 13 months at most |")
    lines += ["", "## Recipients", "",
              f"Your data is intended for {g('company')} and its technical providers: the host ({g('host_name')})"
              + (f", and: {', '.join(sorted(names))}." if names else ".") + " It is never sold.", ""]
    if us:
        lines += ["## Transfers outside the European Union", "",
                  f"Some services ({', '.join(us)}) may process data in the United States. These transfers rely on the safeguards of the GDPR (adequacy decision / standard contractual clauses).", ""]
    lines += ["## Your rights", "",
              f"You have the rights of access, rectification, erasure, restriction, objection and portability, and the right to withdraw consent at any time. To exercise them, write to {g('email')}. We answer within one month. "
              "You may also lodge a complaint with your data protection authority.", "", "## Cookies", "", "See the [cookie policy](/cookie-policy).", ""]
    return "\n".join(lines)


def _cookies(p: dict, services: list, lang: str, host: str, today: date, miss: list[str]) -> str:
    fr = lang == "fr"
    head = ("# Politique de cookies" if fr else "# Cookie policy")
    intro = (f"Un cookie est un petit fichier déposé sur votre appareil. Le site **{host}** utilise les cookies décrits ci-dessous. "
             "Ceux qui ne sont pas strictement nécessaires ne sont déposés qu'avec votre consentement, que vous pouvez modifier à tout moment."
             if fr else f"A cookie is a small file stored on your device. **{host}** uses the cookies described below. "
             "Those that are not strictly necessary are only set with your consent, which you can change at any time.")
    lines = [head, "", f"*{'Dernière mise à jour' if fr else 'Last updated'} : {today.strftime('%d/%m/%Y') if fr else today.isoformat()}*", "", intro, "",
             "## " + ("Cookies strictement nécessaires" if fr else "Strictly necessary cookies"), "",
             ("Ils font fonctionner le site (sécurité, mémorisation de votre choix de cookies). Ils ne demandent pas de consentement." if fr else
              "They make the site work (security, remembering your cookie choice). They do not require consent."), ""]
    if services:
        lines += ["## " + ("Services soumis à votre consentement" if fr else "Services subject to your consent"), "",
                  "| " + ("Service" if fr else "Service") + " | " + ("Finalité" if fr else "Purpose") + " | " + ("Pays" if fr else "Country") + " |", "|---|---|---|"]
        for s in services:
            lines.append(f"| {s['name']} | {PURPOSE[s['category']][lang]} | {s['region']} |")
        lines.append("")
    else:
        lines += [("Aucun service soumis à consentement n'a été détecté sur le site." if fr else "No service subject to consent was detected on the site."), ""]
    lines += ["## " + ("Gérer vos choix" if fr else "Managing your choices"), "",
              ('Vous pouvez modifier votre choix à tout moment avec le lien « Gérer les cookies » du site (`data-mas-cookie-settings`), ou depuis les réglages de votre navigateur.'
               if fr else 'You can change your choice at any time with the "Manage cookies" link of the site (`data-mas-cookie-settings`), or from your browser settings.'), ""]
    return "\n".join(lines)
