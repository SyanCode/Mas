"""Drafts of the legal pages of a site, filled from what Mas knows: the company's details the owner gives and
the services the audit saw on the live site (analytics, embeds, cookies).

French and English. These are starting points to read, complete and have checked, not legal advice: every
field left empty shows as ``[TO COMPLETE]`` and is listed as missing.
"""

from __future__ import annotations

import json
import re
from datetime import date

from mas.db import Database

LANGS = ("fr", "en")
FIELDS = {  # key: (max length, required for the legal notice)
    "company": (120, True), "legal_form": (60, False), "address": (250, True), "siret": (40, False), "vat": (40, False),
    "capital": (40, False), "rcs": (80, False), "email": (120, True), "phone": (40, False),
    "director": (120, True), "host_name": (120, True), "host_address": (250, True), "host_phone": (40, False),
    "dpo": (120, False), "retention_months": (3, False), "newsletter": (5, False), "contact_form": (5, False),
    "extra_services": (300, False),
}
EMAIL_RE = re.compile(r"^[^@\s<>\"']+@[^@\s<>\"']+\.[^@\s<>\"']+$")
TODO = {"fr": "[À COMPLÉTER]", "en": "[TO COMPLETE]"}
PURPOSE = {
    "analytics": {"fr": "mesure d'audience", "en": "audience measurement"},
    "marketing": {"fr": "publicité et suivi des campagnes", "en": "advertising and campaign tracking"},
    "embed": {"fr": "affichage de contenus tiers (vidéos, cartes)", "en": "display of third-party content (videos, maps)"},
    "cdn": {"fr": "chargement de ressources (polices)", "en": "loading of resources (fonts)"},
    "exempt": {"fr": "mesure d'audience", "en": "audience measurement"},
}
TITLES = {
    "legal": {"fr": "Mentions légales", "en": "Legal notice"},
    "privacy": {"fr": "Politique de confidentialité", "en": "Privacy policy"},
    "cookies": {"fr": "Politique de cookies", "en": "Cookie policy"},
}
FILES = {"legal": {"fr": "mentions-legales.md", "en": "legal-notice.md"},
         "privacy": {"fr": "politique-de-confidentialite.md", "en": "privacy-policy.md"},
         "cookies": {"fr": "politique-de-cookies.md", "en": "cookie-policy.md"}}


def clean_profile(raw: dict) -> dict:
    out = {}
    for key, (limit, _) in FIELDS.items():
        value = raw.get(key, "")
        value = " ".join(str(value).split()) if not isinstance(value, bool) else ("true" if value else "")
        if len(value) > limit:
            raise ValueError(f"{key}: at most {limit} characters")
        out[key] = value
    for key in ("email", "dpo"):
        if out[key] and "@" in out[key] and not EMAIL_RE.fullmatch(out[key]):
            raise ValueError(f"{key}: an e-mail address")
    if out["retention_months"] and not out["retention_months"].isdigit():
        raise ValueError("retention_months: a number of months")
    return out


def load(db: Database, app_id: str) -> dict:
    try:
        return clean_profile(json.loads(db.get_setting(f"legal:{app_id}") or "{}"))
    except ValueError:
        return clean_profile({})


def save(db: Database, app_id: str, raw: dict) -> dict:
    profile = clean_profile(raw)
    db.set_setting(f"legal:{app_id}", json.dumps(profile))
    return profile


def _v(profile: dict, key: str, lang: str, missing: list[str]) -> str:
    value = profile.get(key, "")
    if not value:
        missing.append(key)
        return TODO[lang]
    return value


def _services(detected: dict, profile: dict) -> list[dict]:
    services = [s for s in detected.get("services", []) if s["category"] in PURPOSE]
    for name in [x.strip() for x in profile.get("extra_services", "").split(",") if x.strip()]:
        services.append({"name": name, "category": "analytics", "region": "?"})
    return services


def generate(profile: dict, detected: dict, lang: str, host: str, today: date | None = None) -> list[dict]:
    """The three documents: [{id, title, filename, markdown, missing}]."""
    lang = lang if lang in LANGS else "en"
    today = today or date.today()
    services = _services(detected, profile)
    out = []
    for doc_id, fn in (("legal", _legal), ("privacy", _privacy), ("cookies", _cookies)):
        missing: list[str] = []
        body = fn(profile, services, lang, host, today, missing)
        out.append({"id": doc_id, "title": TITLES[doc_id][lang], "filename": FILES[doc_id][lang],
                    "markdown": f"<!-- Draft generated by Mas on {today.isoformat()}: read it, complete it and have it checked. -->\n\n" + body,
                    "missing": list(dict.fromkeys(missing))})
    return out


