"""Legal pages generator: filled from the company's details and the services the audit saw."""

from __future__ import annotations

from datetime import date

from test_cms import SCHEMA, env, login  # noqa: F401

from mas import legal
from mas.compliance import Auditor, Response

PROFILE = {"company": "Dupont SARL", "legal_form": "SARL", "address": "1 rue du Pain, 75001 Paris", "siret": "123 456 789 00010",
           "email": "contact@dupont.fr", "director": "M. Dupont", "host_name": "OVH", "host_address": "2 rue Kellermann, 59100 Roubaix",
           "retention_months": "36"}
DETECTED = {"services": [{"name": "Google Analytics", "category": "analytics", "region": "US"},
                         {"name": "YouTube player", "category": "embed", "region": "US"}], "cookies": ["_ga"]}


def test_complete_profile_gives_complete_pages_without_placeholders():
    docs = {d["id"]: d for d in legal.generate(legal.clean_profile(PROFILE), DETECTED, "fr", "dupont.fr", date(2026, 11, 12))}
    assert all(not d["missing"] for d in docs.values()) and "[À COMPLÉTER]" not in docs["legal"]["markdown"]
    assert "SIRET 123 456 789 00010" in docs["legal"]["markdown"] and "OVH" in docs["legal"]["markdown"]
    privacy = docs["privacy"]["markdown"]
    assert "Google Analytics" in privacy and "États-Unis" in privacy and "36 mois" in privacy and "CNIL" in privacy
    assert "| Google Analytics | mesure d'audience | US |" in docs["cookies"]["markdown"]
    assert docs["privacy"]["filename"] == "politique-de-confidentialite.md"


def test_missing_fields_are_marked_and_listed_and_english_works():
    docs = {d["id"]: d for d in legal.generate(legal.clean_profile({"company": "Acme"}), {"services": []}, "en", "acme.com")}
    assert {"address", "email", "director", "host_name", "host_address"} <= set(docs["legal"]["missing"])
    assert "[TO COMPLETE]" in docs["legal"]["markdown"] and "Legal notice" in docs["legal"]["markdown"]
    assert "No service subject to consent" in docs["cookies"]["markdown"]
    assert "Transfers outside" not in docs["privacy"]["markdown"]  # nothing leaves the EU


def test_generated_pages_pass_the_audit_own_checks():
    """What Mas writes should satisfy what Mas checks."""
    docs = {d["id"]: d for d in legal.generate(legal.clean_profile(PROFILE), DETECTED, "fr", "dupont.fr")}
    page = lambda d: "<html>" + docs[d]["markdown"].replace("#", "") + "</html>"  # noqa: E731
    home = '<html lang="fr"><body><a href="/ml">Mentions légales</a><a href="/pc">Politique de confidentialité</a></body></html>'
    pages = {"https://dupont.fr/": home, "https://dupont.fr/ml": page("legal"), "https://dupont.fr/pc": page("privacy")}
    H = [("strict-transport-security", "x"), ("content-security-policy", "x"), ("x-content-type-options", "x"), ("referrer-policy", "x")]
    fetch = lambda url, follow=True: (Response(url, 301, [("location", "https:" + url[5:])]) if url.startswith("http://")  # noqa: E731
                                      else Response(url, 200, H, pages[url].encode()) if url in pages else Response(url, 404))
    result = Auditor(fetch).audit("dupont.fr")
    ids = {f["id"] for f in result["findings"]}
    assert {"legal-ok", "privacy-ok"} <= ids and "legal-incomplete" not in ids and "privacy-incomplete" not in ids


def test_validation():
    import pytest
    with pytest.raises(ValueError):
        legal.clean_profile({"company": "x" * 200})
    with pytest.raises(ValueError):
        legal.clean_profile({"email": "a@b"})
    with pytest.raises(ValueError):
        legal.clean_profile({"retention_months": "lots"})


def test_api_saves_profile_uses_the_audit_and_commits_files(env):
    client, db, gh = env
    h = {"x-csrf-token": login(client)}
    comp = client.app.state.compliance
    comp.auditor = Auditor(lambda url, follow=True: Response(url, 200, [], b"<html lang='fr'><script src='https://www.googletagmanager.com/gtag/js'></script></html>")
                           if url == "https://client.example.com/" else Response(url, 404))
    comp.run(db.get_app("site"), None, "manual")
    r = client.put("/api/cms/sites/site/legal", headers=h, json=PROFILE)
    assert r.status_code == 200 and r.json()["profile"]["company"] == "Dupont SARL"
    names = {s["name"] for s in r.json()["detected"]["services"]}
    assert "Google Tag Manager" in names and r.json()["audited"] is True
    assert client.put("/api/cms/sites/site/legal", headers=h, json={"email": "nope@"}).status_code == 400
    pub = client.post("/api/cms/sites/site/legal/publish", headers=h, json={"lang": "fr", "folder": "content/legal"})
    assert pub.status_code == 200 and "mentions-legales.md" in pub.json()["files"]
    assert gh.files["content/legal/politique-de-cookies.md"].decode().startswith("<!-- Draft generated by Mas")
    assert gh.commits[-1][0].startswith("cms(legal)")
    assert client.post("/api/cms/sites/site/legal/publish", headers=h, json={"folder": "../etc"}).status_code == 400
    assert client.get("/api/cms/sites/other/legal").status_code in (200, 404)
